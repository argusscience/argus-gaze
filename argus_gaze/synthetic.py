"""SYNTHETIC test data, for software testing only. Never publish it or present it as a
recording: every value is generated by this file, not measured.

It mimics an ET3Space session at a tabletop workcell (the layout in the recording
instructions): a person stands at the table and looks at targets in turn. The geometry is
self-consistent (eye positions, unit gaze directions toward the target with small angular
noise, vergence, surface hits on the tabletop plane) so that the reader, replayer,
convergence computation and consistency checks can be exercised end to end.

ET3Space global frame convention used here (ET3Space Manual section 3.1.1): X forward,
Y to the subject's right, Z down. Units: centimetres.
"""
from __future__ import annotations

import math
import random
from typing import List, Tuple

from . import geometry as g
from . import protocol as p

# Tabletop = plane Z = 0 (surface 0); targets on it, in cm, global frame.
TARGETS = {
    "T1": (35.0, -25.0, 0.0), "T2": (35.0, 0.0, 0.0), "T3": (50.0, 0.0, 0.0),
    "T4": (50.0, 25.0, 0.0), "T5": (65.0, -20.0, 0.0), "T6": (65.0, 20.0, 0.0),
}
EVENT_CODES = {"T1": 11, "T2": 12, "T3": 13, "T4": 14, "T5": 15, "T6": 16}


def _perturb(direction: g.Vec3, sigma_deg: float, rng: random.Random) -> g.Vec3:
    d = g.normalise(direction)
    # random small rotation: add an orthogonal component
    a = (1.0, 0.0, 0.0) if abs(d[0]) < 0.9 else (0.0, 1.0, 0.0)
    u = g.normalise((d[1] * a[2] - d[2] * a[1], d[2] * a[0] - d[0] * a[2], d[0] * a[1] - d[1] * a[0]))
    v = (d[1] * u[2] - d[2] * u[1], d[2] * u[0] - d[0] * u[2], d[0] * u[1] - d[1] * u[0])
    ang = math.radians(rng.gauss(0.0, sigma_deg))
    phi = rng.uniform(0, 2 * math.pi)
    off = g.add(g.scale(u, math.cos(phi) * math.tan(ang)), g.scale(v, math.sin(phi) * math.tan(ang)))
    return g.normalise(g.add(d, off))


def generate(duration_per_target_s: float = 3.0, rate_hz: float = 180.0, noise_deg: float = 0.25,
             seed: int = 7, ipd_cm: float = 6.3) -> List[p.DataRecord]:
    rng = random.Random(seed)
    names = [
        "status", "overtime_count", "mark_value", "xdat", "cu_video_field_num",
        "left_pupil_diam", "right_pupil_diam", "vergence_angle",
        "verg_gaze_coord_x", "verg_gaze_coord_y", "verg_gaze_coord_z",
        "hdtrk_x", "hdtrk_y", "hdtrk_z", "hdtrk_az", "hdtrk_el", "hdtrk_rl",
        "et3s_scene_number", "et3s_gaze_length", "et3s_horz_gaze_coord", "et3s_vert_gaze_coord",
        "left_eye_location_x", "left_eye_location_y", "left_eye_location_z",
        "left_gaze_dir_x", "left_gaze_dir_y", "left_gaze_dir_z", "fix_duration",
    ]
    cs = p.check_state_for(names)
    recs: List[p.DataRecord] = []
    frame = 0
    t = 0.0
    dt = 1.0 / rate_hz
    status_ok = (p.STATUS_LEFT_PUPIL_FOUND | p.STATUS_LEFT_CR_FOUND |
                 p.STATUS_RIGHT_PUPIL_FOUND | p.STATUS_RIGHT_CR_FOUND | 0b10)
    for name, target in TARGETS.items():
        n = int(duration_per_target_s * rate_hz)
        fix_start = t
        for k in range(n):
            # head sways a little; standing ~55 cm above the tabletop (Z down -> negative)
            sway = math.sin(2 * math.pi * 0.3 * t)
            head = (0.0 + 2.0 * sway, 0.0 + 1.5 * math.sin(2 * math.pi * 0.2 * t), -55.0)
            az = math.degrees(math.atan2(target[1] - head[1], target[0] - head[0])) * 0.6
            el = -35.0 + 3.0 * sway
            rot = g.rotation_from_az_el_rl(az, el, 0.0)
            right_axis = (rot[0][1], rot[1][1], rot[2][1])
            left_eye = g.add(head, g.scale(right_axis, -ipd_cm / 2))
            right_eye = g.add(head, g.scale(right_axis, ipd_cm / 2))
            ld = _perturb(g.sub(target, left_eye), noise_deg, rng)
            rd = _perturb(g.sub(target, right_eye), noise_deg, rng)
            cyc = g.normalise(g.add(ld, rd))
            verg = g.angle_deg(ld, rd)
            # cyclopean ray onto the tabletop plane Z = 0
            s = -head[2] / cyc[2] if cyc[2] > 1e-6 else None
            hit = g.add(head, g.scale(cyc, s)) if s else None
            blink = rng.random() < 0.003
            st = (0b10 if blink else status_ok)
            values = {
                "start_of_record": p.START_OF_RECORD, "status": st, "overtime_count": 0,
                "mark_value": 0, "xdat": EVENT_CODES[name] if k < int(0.2 * rate_hz) else 0,
                "cu_video_field_num": frame % 180,
                "left_pupil_diam": 40.0 + rng.gauss(0, 0.3), "right_pupil_diam": 40.5 + rng.gauss(0, 0.3),
                "vergence_angle": verg,
                "verg_gaze_coord_x": cyc[0], "verg_gaze_coord_y": cyc[1], "verg_gaze_coord_z": cyc[2],
                "hdtrk_x": head[0], "hdtrk_y": head[1], "hdtrk_z": head[2],
                "hdtrk_az": az, "hdtrk_el": el, "hdtrk_rl": 0.0,
                "et3s_scene_number": 0 if hit else -1,
                "et3s_gaze_length": s if s else 0.0,
                "et3s_horz_gaze_coord": hit[1] if hit else 0.0,
                "et3s_vert_gaze_coord": hit[0] if hit else 0.0,
                "left_eye_location_x": left_eye[0], "right_eye_location_x": right_eye[0],
                "left_eye_location_y": left_eye[1], "right_eye_location_y": right_eye[1],
                "left_eye_location_z": left_eye[2], "right_eye_location_z": right_eye[2],
                "left_gaze_dir_x": ld[0], "right_gaze_dir_x": rd[0],
                "left_gaze_dir_y": ld[1], "right_gaze_dir_y": rd[1],
                "left_gaze_dir_z": ld[2], "right_gaze_dir_z": rd[2],
                "fix_duration": (t - fix_start) if t - fix_start > 0.1 else 0.0,
            }
            recs.append(p.DataRecord(frame_no=frame, timestamp_100ns=int(round(t * 1e7)),
                                     update_rate=rate_hz, check_state=cs, values=values))
            frame += 1
            t += dt
    return recs


def main(argv=None) -> int:
    import argparse
    from .csvfile import write_csv

    ap = argparse.ArgumentParser(description="Write a SYNTHETIC csv session for software testing only")
    ap.add_argument("--out", required=True)
    ap.add_argument("--seconds-per-target", type=float, default=3.0)
    args = ap.parse_args(argv)
    write_csv(args.out, generate(args.seconds_per_target), version="SYNTHETIC test data - not a recording")
    print("wrote %s (synthetic, for testing only)" % args.out)
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(main())
